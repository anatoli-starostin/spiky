"""Replace the idealised latch with a real inhibitory oscillator and see what it costs.

WHY. The teacher-exact weight-coded result (1e-05 normalised) assumes all 32 selected cells
emit at ONE common time `t_cell`, so the output neuron's membrane sums exp(w/tau) at a
single instant. Cells do not naturally do that. A cell's 6 race bits are only RESOLVED at
the later spike of each pair, so

    r[t,i]      = max(t_a, t_b)                     race i of table t is resolved
    ready[t]    = max_i r[t,i]                      cell t can first know its address

and `ready` is data-dependent. Measured on 20,000 real observations (window T = 1.0):

    ready               mean 0.714, max 0.996
    ACROSS-TABLE SPREAD mean 0.154, max 0.388       <-- the jitter the latch removes
    within-cell race spread  mean 0.196, p99 0.436

So the latch is doing real work. This file asks whether a fixed-period inhibitory rhythm
can do that work instead.

MODEL. Each cell is a coincidence detector on its 6 resolved races, firing when its drive
crosses an inhibition-modulated threshold:

    u[t](tau)  = drive from arrived races        (two memory models, below)
    Theta(tau) = Theta0 + A * phi(tau)           phi in [0,1], period P
    fire       = first tau with u >= Theta

Theta0 = 5 + margin (default 5.2) sits strictly between 5 and 6, so a cell needs ALL SIX
races to match. Address recovery is therefore correct BY CONSTRUCTION -- a 5-of-6 cell can
never cross for any tau_c or waveform. The failure modes are (a) MISSES, a correct cell that
never crosses, and (b) WRONG-CYCLE firing, a cell not ready before release that waits a full
period. Both are counted.

CELL MEMORY -- the modelling choice that turns out to matter most:
  "latch": each arrived race latches persistently, u = #arrived. A ready cell holds its
           address indefinitely and waits for release. Needs a bistable unit.
  "decay": u = sum over arrived races of exp(-(tau - r_i)/tau_c). Pure coincidence, no
           memory -- the drive DECAYS, so a cell held too long silently drops out.

WAVEFORMS: square (hard gate, the closest thing to the ideal latch), sine (smooth threshold
modulation), sawtooth (linear ramp down -> ordered release), and "ing", an EMERGENT rhythm
where the inhibition is generated by the cells themselves:

    Theta(tau) = Theta0 + g * h(tau),   dh/dt = -h/tau_i + (1/N) * sum_c delta(tau - fire_c)

i.e. every cell spike raises a shared inhibitory pool that decays with tau_i. No imposed
clock: the rhythm, if any, is a property of the circuit.

THE P >= T BOUND. Release must come after the last input spike, or cells that are not yet
ready miss their window and fire a full period late. P < T is swept to demonstrate it.

    python inhib_sync.py --quick        # a few configs
    python inhib_sync.py                # the full sweep -> results/inhib_sync.json
"""
import argparse
import json
import math
import os

import numpy as np
import torch

from student import SpikingStudent

HERE = os.path.dirname(os.path.abspath(__file__))
NPZ = os.path.join(HERE, "..", "distill_exp19_100k.npz")
OUT = os.path.join(HERE, "results")
T_WINDOW = 1.0                       # the encoder's latency window, by construction


# ----------------------------------------------------------------------------- geometry
def race_geometry(st, x):
    """-> r [B, 32, 6] race resolution times, sel [B, 32] selected address, ready [B, 32]."""
    t_in = st.enc(x)
    ta, tb = t_in[:, st.anchor_a], t_in[:, st.anchor_b]      # [B, 32, 6]
    r = torch.maximum(ta, tb)
    bits = (tb > ta).to(torch.int64)          # t_a earlier  <=>  x_a > x_b  <=>  bit 1
    sel = (bits * st.powers.view(1, 1, -1)).sum(-1)
    return r, sel, r.max(-1).values


def phi(tau, waveform, P, offset, duty):
    """Inhibition envelope in [0, 1]; 1 = fully suppressed."""
    ph = ((tau - offset) % P) / P
    if waveform == "square":
        return (ph < duty).to(tau.dtype)
    if waveform == "sine":
        return 0.5 * (1.0 + torch.cos(2.0 * math.pi * ph))
    if waveform == "sawtooth":
        return 1.0 - ph
    raise ValueError(waveform)


def drive_params(r, memory, tau_c):
    """Closed form for the drive, valid on the only interval that can ever cross.

    Theta0 lies strictly between 5 and 6, so a cell can only cross once ALL SIX races have
    arrived, i.e. for tau >= ready. On that interval every term is active and

        latch: u(tau) = 6                                  (persistent, flat)
        decay: u(tau) = C * exp(-tau/tau_c),  C = sum_i exp(r_i/tau_c)

    -> ready [B, 32] and C [B, 32]. No [B, 32, 6, S] tensor is ever built, which is what
    makes the 20,000-sample sweep cheap.
    """
    ready = r.max(-1).values
    if memory == "latch":
        return ready, torch.full_like(ready, 6.0)
    return ready, torch.exp(r / tau_c).sum(-1)


def drive_at(tau, ready, C, memory, tau_c):
    """u on a grid: tau [S], ready/C [B, 32] -> [B, 32, S], zero before `ready`."""
    active = (tau.view(1, 1, -1) >= ready.unsqueeze(-1)).to(C.dtype)
    if memory == "latch":
        return active * C.unsqueeze(-1)
    return active * C.unsqueeze(-1) * torch.exp(-tau.view(1, 1, -1) / tau_c)


def release_phase(waveform, P, A, theta0, duty, n=4000, dev="cpu"):
    """Time within one period at which the threshold first drops to where u=6 can cross."""
    ph = torch.linspace(0.0, P, n, device=dev)
    openq = (theta0 + A * phi(ph, waveform, P, 0.0, duty)) <= 6.0
    return float(ph[int(openq.to(torch.uint8).argmax())]) if bool(openq.any()) else float("nan")


def fire_times_clocked(r, waveform, P, A, theta0, offset, duty, memory, tau_c,
                       tau_max, n_steps, chunk=2000):
    """First threshold crossing per cell under an IMPOSED rhythm. -> t_fire [B, 32]."""
    dev = r.device
    tau = torch.linspace(0.0, tau_max, n_steps, device=dev)
    th = theta0 + A * phi(tau, waveform, P, offset, duty)          # [S]
    ready, C = drive_params(r, memory, tau_c)
    out = torch.empty(r.shape[:2], device=dev)
    for i in range(0, r.shape[0], chunk):
        u = drive_at(tau, ready[i:i + chunk], C[i:i + chunk], memory, tau_c)
        cross = u >= th.view(1, 1, -1)
        any_c = cross.any(-1)
        t = tau[cross.to(torch.uint8).argmax(-1)]
        out[i:i + chunk] = torch.where(any_c, t, torch.full_like(t, float("nan")))
    return out


def fire_times_ing(r, g, tau_i, theta0, memory, tau_c, tau_max, n_steps, chunk=20000):
    """EMERGENT rhythm: the cells drive a shared inhibitory pool. Sequential by necessity."""
    dev = r.device
    dt = tau_max / (n_steps - 1)
    ready, C = drive_params(r, memory, tau_c)
    out = torch.full(r.shape[:2], float("nan"), device=dev)
    N = r.shape[1]
    decay = math.exp(-dt / tau_i)
    for i in range(0, r.shape[0], chunk):
        rd, Cc = ready[i:i + chunk], C[i:i + chunk]
        b = rd.shape[0]
        h = torch.zeros(b, 1, device=dev)
        fired = torch.zeros(b, N, dtype=torch.bool, device=dev)
        tf = torch.full((b, N), float("nan"), device=dev)
        for s in range(n_steps):
            tau = s * dt
            u = torch.where(rd <= tau, Cc if memory == "latch"
                            else Cc * math.exp(-tau / tau_c), torch.zeros_like(Cc))
            now = (~fired) & (u >= theta0 + g * h)
            if bool(now.any()):
                tf = torch.where(now, torch.full_like(tf, tau), tf)
                fired |= now
                h = h + now.sum(-1, keepdim=True).to(h.dtype) / N
            h = h * decay
        out[i:i + chunk] = tf
    return out


# ----------------------------------------------------------------------------- readout
def selected_weights(st, sel):
    W = torch.exp(st.w / st.tau)                                  # (32, 64, 6) variant W
    idx = torch.arange(st.n_tables, device=sel.device).view(1, -1)
    return W[idx.expand_as(sel), sel]                             # [B, 32, 6]


def readout(st, Wsel, t_fire, t_rel, neuron, theta_out):
    """Decoded action given per-cell ARRIVAL times.

    Both decoders are the ones derived for SYNCHRONOUS arrivals -- that is the point: the
    oscillator's job is to make that assumption true, and any jitter shows up as error.

    Cells that never fired contribute nothing (a dropped synapse). That is the physically
    honest treatment: the output neuron cannot know a spike was owed to it.
    """
    tau = st.tau
    ok = torch.isfinite(t_fire)
    s = (torch.where(ok, t_fire, torch.zeros_like(t_fire)) - t_rel).unsqueeze(-1)
    m = ok.to(Wsel.dtype).unsqueeze(-1)
    if neuron == "exact":
        # ideal: s == 0 for all cells  =>  S is exactly the teacher's pre-log sum
        S = (Wsel * m * torch.exp(-s / tau)).sum(1)               # [B, 6]
    else:
        e1 = torch.exp(s / tau)
        A_ = (Wsel * m * e1).sum(1)
        B_ = (Wsel * m * e1 * e1).sum(1)
        x = (A_ + torch.sqrt((A_ * A_ - 4.0 * B_ * theta_out).clamp_min(0.0))) \
            / (2.0 * B_).clamp_min(1e-30)
        t_out = -tau * torch.log(x.clamp(1e-30, 1.0 - 1e-7))
        xr = torch.exp(-t_out / tau)
        S = theta_out / (xr * (1.0 - xr)).clamp_min(1e-30)        # analytic inverse
    return st.tph * tau * (torch.log(S.clamp_min(1e-30)) - math.log(st.tph))


def lif_theta(st, Wsel, rho=0.5):
    """theta for the LIF output neuron, fixed at the IDEAL synchronous configuration."""
    S = Wsel.sum(1)                                               # A == B == S when s == 0
    return float(rho * (S * S / (4.0 * S)).min())


def build(dev, n_val=20000):
    Z = np.load(NPZ)
    g = torch.Generator().manual_seed(0)
    perm = torch.randperm(Z["x_norm"].shape[0], generator=g)[:n_val]
    X = torch.tensor(Z["x_norm"][perm.numpy()], dtype=torch.float32, device=dev)
    A = torch.tensor(Z["y_action_mean"][perm.numpy()], dtype=torch.float32, device=dev)
    st = SpikingStudent(torch.tensor(Z["weights"], device=dev),
                        torch.tensor(Z["anchor_a"], device=dev).long(),
                        torch.tensor(Z["anchor_b"], device=dev).long(),
                        float(Z["tau"]), neuron="exact", variant="W", scope="races").to(dev)
    for p in st.parameters():
        p.requires_grad_(False)
    return st, X, A, float(torch.tensor(Z["y_action_mean"]).std())


def run_cfg(st, X, A, astd, cfg, n_steps, dev, geom=None):
    r, sel, ready = geom if geom is not None else race_geometry(st, X)
    Wsel = selected_weights(st, sel)
    theta_out = lif_theta(st, Wsel)
    latest = float(ready.max())
    P = cfg["P"]
    if cfg["waveform"] == "ing":
        tau_max = latest + 8.0 * cfg["tau_i"] + 0.5
        t_fire = fire_times_ing(r, cfg["g"], cfg["tau_i"], cfg["theta0"], cfg["memory"],
                                cfg["tau_c"], tau_max, n_steps)
        t_nominal = float("nan")
    else:
        rp = release_phase(cfg["waveform"], P, cfg["A"], cfg["theta0"], cfg["duty"])
        # "aligned": shift the clock so the release lands JUST AFTER the last input spike,
        # which is the P >= T condition made operational. "free": offset 0, clock unaware
        # of the data, so the release lands wherever the period happens to put it.
        off = (latest + 0.02 - rp) if cfg["aligned"] else cfg["offset"]
        cfg = dict(cfg, offset=off)
        tau_max = off + 2.0 * P + latest + 0.2
        t_fire = fire_times_clocked(r, cfg["waveform"], P, cfg["A"], cfg["theta0"],
                                    off, cfg["duty"], cfg["memory"],
                                    cfg["tau_c"], tau_max, n_steps)
        tt = torch.linspace(0.0, tau_max, n_steps, device=dev)
        openq = (cfg["theta0"] + cfg["A"] * phi(tt, cfg["waveform"], P, off,
                                                cfg["duty"])) <= 6.0
        t_nominal = float(tt[int(openq.to(torch.uint8).argmax())]) if bool(openq.any()) \
            else float(tt[-1])
    ok = torch.isfinite(t_fire)
    # The decoder's reference is the POPULATION MEDIAN firing time, not a nominal clock
    # phase. Any real decoder calibrates to what it receives, and using the median makes
    # the comparison purely about ARRIVAL SPREAD -- which is the question being asked.
    t_rel = torch.nanmedian(t_fire) if bool(ok.any()) else torch.tensor(0.0, device=dev)
    miss = 1.0 - float(ok.float().mean())
    jit = torch.where(ok, t_fire, torch.full_like(t_fire, float("nan")))
    per_sample_std = torch.tensor(
        np.nanstd(jit.cpu().numpy(), axis=1)).float()
    span = torch.tensor(np.nanmax(jit.cpu().numpy(), axis=1)
                        - np.nanmin(jit.cpu().numpy(), axis=1)).float()
    a = readout(st, Wsel, t_fire, t_rel, cfg["neuron"], theta_out)
    err = (a - A).abs()
    # cells that fired a whole period late (the P < T failure mode)
    late = float(((t_fire - t_rel) > 0.5 * P).float().mean()) if cfg["waveform"] != "ing" \
        else float("nan")
    return dict(cfg=cfg, latest_ready=latest, t_rel=float(t_rel), t_nominal=t_nominal,
                miss_rate=miss, late_rate=late,
                jitter_std=float(np.nanmean(per_sample_std.numpy())),
                jitter_span=float(np.nanmean(span.numpy())),
                jitter_span_max=float(np.nanmax(span.numpy())),
                mean_err=float(err.mean()), max_err=float(err.max()),
                norm_mean=float(err.mean()) / astd, norm_max=float(err.max()) / astd)


def ideal_latch(st, X, A, astd, neuron, geom):
    """The reference: a perfect latch releasing all 32 cells after the last input."""
    r, sel, ready = geom
    Wsel = selected_weights(st, sel)
    t_rel = float(ready.max()) + 1e-6
    t_fire = torch.full_like(ready, t_rel)
    a = readout(st, Wsel, t_fire, t_rel, neuron, lif_theta(st, Wsel))
    e = (a - A).abs()
    return dict(cfg=dict(waveform="IDEAL-LATCH", neuron=neuron, memory="-", P=float("nan"),
                         A=float("nan"), tau_c=float("nan"), theta0=float("nan"),
                         offset=float("nan"), duty=float("nan")),
                latest_ready=t_rel, t_rel=t_rel, t_nominal=float('nan'), miss_rate=0.0, late_rate=0.0,
                jitter_std=0.0, jitter_span=0.0, jitter_span_max=0.0,
                mean_err=float(e.mean()), max_err=float(e.max()),
                norm_mean=float(e.mean()) / astd, norm_max=float(e.max()) / astd)


def no_sync(st, X, A, astd, neuron, geom):
    """The other reference: NO oscillator at all -- each cell fires the instant it is ready."""
    r, sel, ready = geom
    Wsel = selected_weights(st, sel)
    t_rel = float(ready.mean())
    a = readout(st, Wsel, ready, t_rel, neuron, lif_theta(st, Wsel))
    e = (a - A).abs()
    sp = (ready.max(1).values - ready.min(1).values)
    return dict(cfg=dict(waveform="NO-SYNC", neuron=neuron, memory="-", P=float("nan"),
                         A=float("nan"), tau_c=float("nan"), theta0=float("nan"),
                         offset=float("nan"), duty=float("nan")),
                latest_ready=float(ready.max()), t_rel=t_rel, t_nominal=float('nan'), miss_rate=0.0, late_rate=0.0,
                jitter_std=float(ready.std(1).mean()), jitter_span=float(sp.mean()),
                jitter_span_max=float(sp.max()),
                mean_err=float(e.mean()), max_err=float(e.max()),
                norm_mean=float(e.mean()) / astd, norm_max=float(e.max()) / astd)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-val", type=int, default=20000)
    ap.add_argument("--steps", type=int, default=1200)
    ap.add_argument("--ing-steps", type=int, default=600)
    ap.add_argument("--theta0", type=float, default=5.2)
    ap.add_argument("--tau-c", type=float, default=1.0)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--tag", default="inhib_sync")
    a = ap.parse_args()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    st, X, A, astd = build(dev, a.n_val)
    geom = race_geometry(st, X)
    os.makedirs(OUT, exist_ok=True)
    print(f"device {dev}  val {tuple(X.shape)}  action std {astd:.4f}  "
          f"T={T_WINDOW}  latest ready {float(geom[2].max()):.4f}")

    res = []
    for neuron in ("exact", "lif"):
        for fn in (ideal_latch, no_sync):
            r = fn(st, X, A, astd, neuron, geom)
            res.append(r)
            print(f"{r['cfg']['waveform']:<12} {neuron:5s}  jit_span {r['jitter_span']:.4f}"
                  f"  norm_mean {r['norm_mean']:.5f}  norm_max {r['norm_max']:.4f}",
                  flush=True)

    Ps = [0.75, 1.0, 1.25, 1.5, 2.0]
    As = [2.0, 10.0, 50.0]
    tau_cs = [0.5, 1.0, 3.0, 10.0]
    if a.quick:
        Ps, As, tau_cs = [0.75, 1.25], [10.0], [1.0]
    jobs = []
    for waveform in ("square", "sine", "sawtooth"):
        amps = [10.0] if waveform == "square" else As     # A is irrelevant for a hard gate
        for memory in ("latch", "decay"):
            for neuron in ("exact", "lif"):
                for P in Ps:
                    for Amp in amps:
                        for aligned in (False, True):
                            jobs.append(dict(waveform=waveform, memory=memory,
                                             neuron=neuron, P=P * T_WINDOW, A=Amp,
                                             theta0=a.theta0, tau_c=a.tau_c, offset=0.0,
                                             duty=0.5, aligned=aligned))
    # dedicated tau_c sub-sweep: how much cell MEMORY does a held release actually need?
    for waveform in ("square", "sine", "sawtooth"):
        for neuron in ("exact", "lif"):
            for tc in tau_cs:
                jobs.append(dict(waveform=waveform, memory="decay", neuron=neuron,
                                 P=1.5 * T_WINDOW, A=10.0, theta0=a.theta0, tau_c=tc,
                                 offset=0.0, duty=0.5, aligned=True))
    for memory in ("latch", "decay"):
        for neuron in ("exact", "lif"):
            for tau_i in ([0.3] if a.quick else [0.1, 0.3, 1.0]):
                for gg in ([20.0] if a.quick else [5.0, 20.0]):
                    jobs.append(dict(waveform="ing", memory=memory, neuron=neuron,
                                     P=float("nan"), A=float("nan"), g=gg, tau_i=tau_i,
                                     theta0=a.theta0, tau_c=a.tau_c, offset=0.0, duty=0.5,
                                     aligned=False))
    print(f"\n{len(jobs)} configs\n")
    for i, cfg in enumerate(jobs, 1):
        ns = a.ing_steps if cfg["waveform"] == "ing" else a.steps
        r = run_cfg(st, X, A, astd, cfg, ns, dev, geom=geom)
        res.append(r)
        extra = (f"tau_i={cfg['tau_i']:g} g={cfg['g']:g}" if cfg["waveform"] == "ing"
                 else f"P={cfg['P']:g} A={cfg['A']:g} "
                      f"{'align' if cfg['aligned'] else 'free '} tc={cfg['tau_c']:g}")
        print(f"[{i}/{len(jobs)}] {cfg['waveform']:<8} {cfg['memory']:5s} "
              f"{cfg['neuron']:5s} {extra:<32} t_rel {r['t_rel']:.3f}  "
              f"jit_span {r['jitter_span']:.4f}  miss {r['miss_rate']:.4f}  "
              f"norm_mean {r['norm_mean']:.5f}  norm_max {r['norm_max']:.3f}", flush=True)
        json.dump(res, open(os.path.join(OUT, f"{a.tag}.json"), "w"), indent=1)
    print(f"\nwrote {os.path.join(OUT, a.tag)}.json  ({len(res)} rows)")


if __name__ == "__main__":
    main()
